// build-vendor.mjs — copies the installed @electric-sql/pglite dist files into app/vendor/pglite/
// so the browser app is served entirely from this origin (no CDN) and the service worker can
// precache every byte the engine needs. Also copies notes-db.mjs next to app.js so app/ is
// self-contained, and writes app/precache-manifest.js (the list + a version hash) for sw.js.
//
// Run after `npm install`:   node build-vendor.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const here = path.dirname(new URL(import.meta.url).pathname);
const pkgDir = path.join(here, 'node_modules', '@electric-sql', 'pglite');
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
const dist = path.join(pkgDir, 'dist');
const out = path.join(here, 'app', 'vendor', 'pglite');

// Only what the browser ESM entry (dist/index.js) can reach: its chunks, the fs/ shims it
// dynamically imports, and the three binary assets it fetches relative to import.meta.url.
const keep = (f) => /^(index|chunk-[A-Za-z0-9]+)\.js$/.test(f) || /^(pglite\.wasm|pglite\.data|initdb\.wasm)$/.test(f);
fs.rmSync(out, {recursive: true, force: true});
fs.mkdirSync(path.join(out, 'fs'), {recursive: true});
const copied = [];
for (const f of fs.readdirSync(dist)) if (keep(f)) { fs.copyFileSync(path.join(dist, f), path.join(out, f)); copied.push(`vendor/pglite/${f}`); }
for (const f of fs.readdirSync(path.join(dist, 'fs'))) if (/\.js$/.test(f)) { fs.copyFileSync(path.join(dist, 'fs', f), path.join(out, 'fs', f)); copied.push(`vendor/pglite/fs/${f}`); }
fs.copyFileSync(path.join(here, 'notes-db.mjs'), path.join(here, 'app', 'notes-db.mjs'));
fs.writeFileSync(path.join(out, 'LICENSE-NOTE.txt'), `Copied verbatim from @electric-sql/pglite@${pkg.version} (${pkg.license ?? 'see package'}) by build-vendor.mjs. Do not edit.\n`);

const shell = ['./', 'index.html', 'app.js', 'notes-db.mjs', 'precache-manifest.js'];
const assets = [...shell, ...copied.sort()];
const hash = crypto.createHash('sha256');
for (const a of assets) { const p = path.join(here, 'app', a === './' ? 'index.html' : a); if (fs.existsSync(p) && a !== 'precache-manifest.js') hash.update(fs.readFileSync(p)); }
const version = `ep04-notes-v${pkg.version}-${hash.digest('hex').slice(0, 10)}`;
fs.writeFileSync(path.join(here, 'app', 'precache-manifest.js'), `// generated by build-vendor.mjs — do not edit\nself.__PRECACHE_VERSION = ${JSON.stringify(version)};\nself.__PRECACHE_ASSETS = ${JSON.stringify(assets, null, 1)};\n`);

const bytes = copied.reduce((a, f) => a + fs.statSync(path.join(here, 'app', f)).size, 0);
console.log(`copied ${copied.length} files (${(bytes / 1e6).toFixed(1)} MB) from @electric-sql/pglite@${pkg.version} → app/vendor/pglite/`);
console.log(`precache version ${version}, ${assets.length} assets listed in app/precache-manifest.js`);

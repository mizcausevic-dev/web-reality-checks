// Episode 19 fixture: static generation of ONE synthetic article in two forms.
//
//   dist/csr/article/index.html  CLIENT-RENDERED: an application shell. The article is NOT in the
//                                 HTML; /csr/app.js fetches /article.json and inserts it.
//   dist/ssg/article/index.html  STATICALLY GENERATED: the article IS in the HTML at build time.
//   dist/csr/app.js               the client renderer (same renderArticle() as the generator, serialised)
//   dist/article.json             the data the client renderer fetches
//
// Both variants share: <title>, <meta name="description">, <meta name="robots">, heading structure,
// ordinary <a href> links, article text. Only WHEN the article enters the document differs.
// No framework, no hydration: a static non-interactive article needs none.
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
export const dist = path.join(here, 'dist');
export const article = JSON.parse(fs.readFileSync(path.join(here, 'article.json'), 'utf8'));

// Escaping is minimal and explicit; the data is synthetic and controlled by this fixture.
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// ONE renderer for both variants. Used at build time for SSG; its source text is shipped to the
// browser for CSR, so the eventual DOM of both pages is built from identical markup rules.
// It must stay self-contained (no closures) because it is serialised with Function.prototype.toString.
export function renderArticle(a) {
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  let h = `<article>\n<h1>${esc(a.title)}</h1>\n<p class="lede">${esc(a.description)}</p>\n`;
  for (const s of a.sections) {
    h += `<section>\n<h2>${esc(s.heading)}</h2>\n`;
    for (const p of s.paragraphs) h += `<p>${esc(p)}</p>\n`;
    h += `</section>\n`;
  }
  h += `<nav aria-label="Related">\n<h2>Related</h2>\n<ul>\n`;
  for (const l of a.links) h += `<li><a href="${esc(l.href)}">${esc(l.text)}</a></li>\n`;
  h += `</ul>\n</nav>\n</article>\n`;
  return h;
}

// Identical <head> for both variants. ROBOTS DECISION: this fixture is a local teaching artefact and
// must never be indexed if it is ever deployed by mistake, so BOTH variants carry
// <meta name="robots" content="noindex">. The value comes from article.json ("robots") so the
// decision is data, not an accident of one template. See README "Robots and indexing".
const head = (variant) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(article.title)}</title>
<meta name="description" content="${esc(article.description)}">
<meta name="robots" content="${esc(article.robots)}">
<meta name="x-fixture-variant" content="${variant}">
<style>body{font:18px/1.5 system-ui,sans-serif;max-width:46rem;margin:3rem auto;padding:0 1rem;color:#222}h1{font-size:2rem}.lede{color:#555}.shell{color:#888}</style>
</head>
<body>
`;
const foot = `</body>
</html>
`;

export const csrHtml = () => head('csr') + `<main id="app"><p class="shell">Loading article…</p></main>
<script src="/csr/app.js"></script>
` + foot;

export const ssgHtml = () => head('ssg') + `<main id="app">
${renderArticle(article)}</main>
` + foot;

// The client renderer. It is the same renderArticle() function, serialised. It fetches the article,
// replaces the shell and sets a marker attribute once the DOM has been populated.
export const appJs = () => `// ep19 fixture client renderer (generated by build.mjs — do not edit)
${renderArticle.toString()}
(async () => {
  const root = document.getElementById('app');
  try {
    const r = await fetch('/article.json');
    if (!r.ok) throw new Error('article.json ' + r.status);
    const a = await r.json();
    root.innerHTML = renderArticle(a);
    document.documentElement.setAttribute('data-rendered-by', 'client-js');
  } catch (e) {
    root.innerHTML = '<p class="shell">Could not load the article (' + String(e && e.message) + ').</p>';
  }
})();
`;

export function build() {
  fs.rmSync(dist, {recursive: true, force: true});
  const write = (rel, body) => { const p = path.join(dist, rel); fs.mkdirSync(path.dirname(p), {recursive: true}); fs.writeFileSync(p, body); return p; };
  const out = {
    csr: write('csr/article/index.html', csrHtml()),
    ssg: write('ssg/article/index.html', ssgHtml()),
    appJs: write('csr/app.js', appJs()),
    data: write('article.json', JSON.stringify(article, null, 2) + '\n'),
  };
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = build();
  for (const [k, p] of Object.entries(out)) console.log(`${k.padEnd(6)} ${path.relative(here, p)}  ${fs.statSync(p).size} bytes`);
}

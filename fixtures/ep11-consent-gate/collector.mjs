// Episode 11 fixture: SIMULATED ANALYTICS · LOCAL COLLECTOR. Loopback only. Synthetic data only.
//
// This is NOT a real analytics or advertising service and contacts none. It records exactly what
// the simulated page sends it, one envelope per POST, so that the number of optional analytics
// requests can be counted per consent state. It applies no filtering of its own: if a request
// reaches it, the page sent it. Nothing here can "un-receive" a request.
//
//   POST /collect   body: {event, category, module, consentState, pageMode, ts} -> 202, stored verbatim (+ seq)
//   GET  /events    -> {label, count, events}
//   POST /reset     -> clears the store (used between scenario runs)
import http from 'node:http';

export const COLLECTOR_LABEL = 'SIMULATED ANALYTICS · LOCAL COLLECTOR';
const REQUIRED = ['event', 'category', 'module', 'consentState', 'pageMode', 'ts'];

export const createCollector = () => {
  const events = [];
  const json = (res, code, body) => { res.writeHead(code, {'content-type': 'application/json'}); res.end(JSON.stringify(body)); };
  const readBody = (req) => new Promise((r) => { let b = ''; req.on('data', (c) => (b += c)); req.on('end', () => r(b)); });

  const app = http.createServer(async (req, res) => {
    const url = new URL(req.url, 'http://127.0.0.1');
    if (req.method === 'POST' && url.pathname === '/collect') {
      let env;
      try { env = JSON.parse(await readBody(req)); } catch { return json(res, 400, {error: 'invalid json'}); }
      const missing = REQUIRED.filter((k) => !(k in env));
      if (missing.length) return json(res, 400, {error: 'envelope missing fields', missing});
      // clientId is a cookieless identifier generated by the simulated module; stored to show that
      // identification does not require a cookie. No real identifier of any kind is involved.
      const stored = {seq: events.length + 1, event: env.event, category: env.category, module: env.module, consentState: env.consentState, pageMode: env.pageMode, clientId: env.clientId ?? null, ts: env.ts};
      events.push(stored); // stored verbatim; the collector has no opinion about consent
      return json(res, 202, {accepted: true, seq: stored.seq, label: COLLECTOR_LABEL});
    }
    if (req.method === 'GET' && url.pathname === '/events') return json(res, 200, {label: COLLECTOR_LABEL, count: events.length, events});
    if (req.method === 'POST' && url.pathname === '/reset') { events.length = 0; return json(res, 200, {ok: true}); }
    json(res, 404, {error: 'not found'});
  });

  const listen = () => new Promise((r) => app.listen(0, '127.0.0.1', () => r(`http://127.0.0.1:${app.address().port}`)));
  const close = () => new Promise((r) => app.close(() => r()));
  return {app, events, listen, close};
};

if (import.meta.url === `file://${process.argv[1]}`) createCollector().listen().then((u) => console.log(`${COLLECTOR_LABEL} on ${u}`));

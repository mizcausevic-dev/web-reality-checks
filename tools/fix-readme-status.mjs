#!/usr/bin/env node
// Removes build-stage status lines ("no MP4 rendered", "the orchestrator will render", "--no-audio estimate")
// from film READMEs once a render exists, and appends a data-driven "## Render evidence" section where missing.
// Idempotent. Usage: node tools/fix-readme-status.mjs
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const STALE = /(orchestrator|--no-audio|no mp4|no narration|no audio generated|not generated by this build|not produced by this build|no video rendered|not executed here: narration|Not executed: (narration|audio)|Blocked: narration|Blocked \(by (spec|design)[^)]*\): (no )?narration|Not executed: audio|None exists yet)/i;
// Mixed lines that hold a real limit: keep only the real part.
const REWRITE = new Map([
  ['ep20', [[/^- Blocked: no packet capture, no real TLS session, no narration audio, no render.*$/m, '- Blocked: no packet capture and no real TLS session; the episode is conceptual.']]],
  ['ep23', [[/^- Blocked \/ not executed: no real browsers, no narration audio.*$/m, '- Blocked / not executed: no real browsers.']]],
  ['ep24', [[/^- Blocked \/ not executed: no real browser, CDN or proxy; no narration audio.*$/m, '- Blocked / not executed: no real browser, CDN or proxy.']]],
]);
const REVIEWED = new Set((process.env.REVIEWED ?? '').split(',').filter(Boolean));
const ids = fs.readdirSync(path.join(root, 'episodes')).filter((d) => /^(ep|cm|qz)\d\d$/.test(d) && fs.existsSync(path.join(root, 'episodes', d, 'render-evidence.json')));
let changed = 0, removed = 0, added = 0;
for (const id of ids) {
  const p = path.join(root, 'episodes', id, 'README.md');
  if (!fs.existsSync(p)) continue;
  let t = fs.readFileSync(p, 'utf8');
  const before = t;
  for (const [re, rep] of REWRITE.get(id) ?? []) t = t.replace(re, rep);
  const out = [];
  let fence = false, inEvidence = false;
  for (const line of t.split('\n')) {
    if (/^```/.test(line)) fence = !fence;
    if (/^## /.test(line)) inEvidence = /^## Render evidence/.test(line);
    if (!fence && !inEvidence && STALE.test(line) && !/^#/.test(line)) { removed++; continue; }
    out.push(line);
  }
  t = out.join('\n').replace(/^## Build and render \(orchestrator\)/m, '## Build and render').replace(/^## Orchestrator note \(observed during production\)/m, '## Test timing note (observed during production)').replace(/\n{3,}/g, '\n\n');
  t = t.replace(/\n+## Render evidence[^\n]*\n[\s\S]*?(?=\n## |$)/, '\n'); // regenerate the section every run so bytes and durations never go stale
  {
    const ev = JSON.parse(fs.readFileSync(path.join(root, 'episodes', id, 'render-evidence.json'), 'utf8'));
    const aud = ev.audio ? `${ev.audio.codec} audio` : 'no audio';
    t = t.replace(/\s*$/, '\n') + `\n## Render evidence\n- Executed: narration generated with ElevenLabs (voice Benedict - Premium British (RP) Male, eleven_v4) and saved to video/public/${id}/narration.mp3; scene boundaries are placed from detected silences or word timestamps, which is a heuristic and can be about a second off the spoken words.\n- Executed: node tools/render.mjs ${id} → episodes/${id}/${id}.mp4 (${ev.video.codec} ${ev.video.width}x${ev.video.height} ${ev.video.fps} fps ${ev.video.pix_fmt}, ${aud}, ${ev.duration_s} s, ${ev.bytes} bytes). Thumbnail and hero are rendered as Remotion stills.\n- Verified: see VERIFICATION.md for the independent ffprobe pass and fixture test results.\n${REVIEWED.has(id) ? '- Observed: inspection stills in frames/ were reviewed for clipping and overlap.\n' : ''}`;
    added++;
  }
  if (t !== before) { fs.writeFileSync(p, t); changed++; }
}
console.log(JSON.stringify({films: ids.length, changed, removedLines: removed, evidenceSectionsAdded: added}));
